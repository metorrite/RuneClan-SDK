#!/usr/bin/env python3
"""Generate the SDK's data types and route table from spec/openapi.json.

    python3 tools/gen_model.py            # write src/main/java/com/runeclans/sdk/model/*.java and Routes.java
    python3 tools/gen_model.py --check    # exit 1 when the committed files differ from what the spec gives

Data shapes only: every components.schemas entry the public operations use becomes a Java record (nested
objects become nested records). Unknown fields are ignored, so a hub that adds a field never breaks an
older SDK. The friendly methods in RuneClanClient are written by hand on top of these.
"""
import json
import keyword
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "openapi.json"
PKG_DIR = ROOT / "src" / "main" / "java" / "com" / "runeclans" / "sdk"
MODEL_DIR = PKG_DIR / "model"
ROUTES = PKG_DIR / "Routes.java"
HEADER = "// Generated by tools/gen_model.py from spec/openapi.json. Do not edit by hand.\n"
METHODS = ["get", "put", "post", "delete", "patch"]
JAVA_KEYWORDS = set("""abstract assert boolean break byte case catch char class const continue default do double else enum extends final
finally float for goto if implements import instanceof int interface long native new package private protected public return short static
strictfp super switch synchronized this throw throws transient try void volatile while true false null record var yield sealed permits""".split())
# Names a record component must not take (they clash with Object / Record methods).
RESERVED_COMPONENTS = {"hashCode", "toString", "equals", "getClass", "notify", "notifyAll", "wait", "clone", "finalize"}
SCOPE_RE = re.compile(r"Needs the scope `([a-z:_]+)`\.?(?: \(or ([a-z:_]+)\))?")


def pascal(name):
    parts = re.split(r"[^A-Za-z0-9]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not out or out[0].isdigit():
        out = "X" + out
    return out


def camel_ident(name):
    p = pascal(name)
    ident = p[:1].lower() + p[1:]
    if ident in JAVA_KEYWORDS or ident in RESERVED_COMPONENTS:
        ident += "Value"
    return ident


def javadoc(text, indent):
    if not text:
        return ""
    text = text.replace("*/", "*&#47;").replace("@", "&#64;").replace("<", "&lt;").replace(">", "&gt;")
    return f"{indent}/** {text} */\n"


def merged(schema):
    """allOf of objects: one object with every part's properties."""
    if "allOf" not in schema:
        return schema
    props, required, desc = {}, [], schema.get("description")
    for part in schema["allOf"]:
        part = merged(part)
        props.update(part.get("properties", {}))
        required += part.get("required", [])
        desc = desc or part.get("description")
    return {"type": "object", "properties": props, "required": required, "description": desc}


class Gen:
    def __init__(self, spec):
        self.spec = spec
        self.schemas = spec["components"]["schemas"]
        self.imports = set()

    def base_type(self, schema):
        t = schema.get("type")
        if isinstance(t, list):
            non_null = [x for x in t if x != "null"]
            t = non_null[0] if len(non_null) == 1 else None
        return t

    def java_type(self, schema, owner_nested, hint):
        """Java type for a property schema; nested object records are appended to owner_nested."""
        if "$ref" in schema:
            name = schema["$ref"].split("/")[-1]
            return name
        schema = merged(schema)
        t = self.base_type(schema)
        if t == "string":
            return "String"
        if t == "integer":
            return "Long"
        if t == "number":
            return "Double"
        if t == "boolean":
            return "Boolean"
        if t == "array":
            items = schema.get("items", {})
            inner = self.java_type(items, owner_nested, hint + "Item")
            self.imports.add("java.util.List")
            return f"List<{inner}>"
        if t == "object" or (t is None and "properties" in schema):
            props = schema.get("properties")
            addl = schema.get("additionalProperties")
            if props:
                owner_nested.append((hint, schema))
                return hint
            if isinstance(addl, dict) and addl:
                inner = self.java_type(addl, owner_nested, hint + "Value")
                self.imports.add("java.util.Map")
                return f"Map<String, {inner}>"
        self.imports.add("com.fasterxml.jackson.databind.JsonNode")
        return "JsonNode"

    def record(self, name, schema, indent, top):
        schema = merged(schema)
        nested = []
        comps = []
        used = set()
        for prop, ps in (schema.get("properties") or {}).items():
            ident = camel_ident(prop)
            while ident in used:
                ident += "_"
            used.add(ident)
            hint = pascal(prop)
            if hint == name:
                hint += "Part"
            jt = self.java_type(ps, nested, hint)
            doc = ps.get("description") if "$ref" not in ps else None
            enum = ps.get("enum")
            if enum:
                doc = (doc + " " if doc else "") + "One of: " + ", ".join(str(e) for e in enum if e is not None) + "."
            annot = "" if ident == prop else f'@JsonProperty("{prop}") '
            if annot:
                self.imports.add("com.fasterxml.jackson.annotation.JsonProperty")
            comps.append((doc, f"{annot}{jt} {ident}"))
        self.imports.add("com.fasterxml.jackson.annotation.JsonIgnoreProperties")
        out = javadoc(schema.get("description"), indent)
        out += f"{indent}@JsonIgnoreProperties(ignoreUnknown = true)\n"
        mods = "public " if top else "public "
        if not comps:
            out += f"{indent}{mods}record {name}() {{}}\n"
            return out
        lines = []
        for i, (doc, decl) in enumerate(comps):
            sep = "," if i < len(comps) - 1 else ""
            lines.append(javadoc(doc, indent + "        ") + f"{indent}        {decl}{sep}\n")
        body = ""
        seen = set()
        for nname, nschema in nested:
            if nname in seen:
                continue
            seen.add(nname)
            body += "\n" + self.record(nname, nschema, indent + "    ", False)
        out += f"{indent}{mods}record {name}(\n" + "".join(lines) + f"{indent}) {{" + (body + indent if body else "") + "}\n"
        return out

    def model_file(self, name):
        self.imports = set()
        body = self.record(name, self.schemas[name], "", True)
        imports = "".join(f"import {i};\n" for i in sorted(self.imports))
        return f"{HEADER}package com.runeclans.sdk.model;\n\n{imports}\n{body}"

    def routes_file(self):
        rows = []
        for path, item in self.spec["paths"].items():
            for m in METHODS:
                op = item.get(m)
                if not op:
                    continue
                desc = op.get("description", "")
                scopes = []
                match = SCOPE_RE.search(desc)
                if match:
                    scopes = [s for s in match.groups() if s]
                keyed = any("apiKey" in sec for sec in op.get("security", self.spec.get("security", [])))
                ok = next((op["responses"][c] for c in ("200", "201", "202", "204") if c in op.get("responses", {})), {})
                content = ok.get("content", {})
                media = next(iter(content), None)
                rtype = None
                if media == "application/json":
                    sch = content[media].get("schema", {})
                    rtype = sch["$ref"].split("/")[-1] if "$ref" in sch else None
                const = m.upper() + "_" + "_".join(
                    re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", seg.strip("{}")).upper().replace("-", "_").replace(".", "_")
                    for seg in path.split("/")[2:] if seg)
                if path == "/health" or path.startswith("/health/"):
                    const = m.upper() + "_" + path.strip("/").upper().replace("/", "_")
                rows.append((const, m.upper(), path, scopes, keyed, rtype, media, op.get("summary", "")))
        consts = set()
        out = [HEADER, "package com.runeclans.sdk;\n\n", "import java.util.List;\n\n",
               "/**\n * Every public hub operation, from {@code spec/openapi.json}. Use one with {@link RuneClanClient#route(Route)} for an operation\n"
               " * that has no friendly method yet. {@code scopes} lists the scopes of which the key needs one (empty: any key).\n */\n",
               "public final class Routes {\n    private Routes() {}\n\n"]
        for const, method, path, scopes, keyed, rtype, media, summary in rows:
            assert const not in consts, const
            consts.add(const)
            scope_list = "List.of(" + ", ".join(f'"{s}"' for s in scopes) + ")"
            rt = f"{rtype}.class" if rtype else "null"
            if rtype:
                rt = f"com.runeclans.sdk.model.{rtype}.class"
            med = f'"{media}"' if media else "null"
            out.append(javadoc(summary, "    "))
            out.append(f'    public static final Route {const} = new Route("{method}", "{path}", {scope_list}, {str(keyed).lower()}, {med}, {rt});\n')
        out.append("\n    /** Every route above, in spec order. */\n    public static final List<Route> ALL = List.of(\n")
        out.append(",\n".join(f"            {r[0]}" for r in rows) + ");\n}\n")
        return "".join(out)

    def outputs(self):
        files = {MODEL_DIR / f"{n}.java": self.model_file(n) for n in sorted(self.schemas)}
        files[ROUTES] = self.routes_file()
        return files


def main():
    check = "--check" in sys.argv
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    files = Gen(spec).outputs()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    extra = [p for p in MODEL_DIR.glob("*.java") if p not in files] if MODEL_DIR.exists() else []
    if check:
        for p in stale + extra:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale or extra:
            print("Run python3 tools/gen_model.py and commit the result.")
            return 1
        print(f"generated code matches the spec ({len(files)} files)")
        return 0
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    for p in extra:
        p.unlink()
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files ({len(stale)} changed, {len(extra)} removed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
